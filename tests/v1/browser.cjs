const path=require('node:path');
const fs=require('node:fs');
const output=process.env.KYOTO_TEST_OUTPUT || path.join(__dirname,'..','build','test-artifacts');
fs.mkdirSync(output,{recursive:true});
const {chromium}=require('playwright');
(async()=>{
 const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox','--enable-unsafe-swiftshader','--use-angle=swiftshader']});
 const context=await browser.newContext({viewport:{width:1152,height:768}});
 const page=await context.newPage();
 const errors=[];
 page.on('console',m=>{if(m.type()==='error'){errors.push(m.text());console.log('CONSOLE',m.text());}});
 page.on('pageerror',e=>{errors.push(e.message);console.log('ERROR',e.message);});
 await page.goto('http://127.0.0.1:8765');
 await page.waitForFunction(()=>!document.getElementById('status'),{},{timeout:60000});
 await page.waitForTimeout(1800);
 await page.screenshot({path:path.join(output,'title.png')});
 await page.keyboard.press('Enter');
 await page.waitForTimeout(700);
 await page.screenshot({path:path.join(output,'opening.png')});
 const click=async(x,y,ms=1300)=>{await page.mouse.click(x*.75,y*.75);await page.waitForTimeout(ms);};
 const key=async(k,ms=300)=>{await page.keyboard.press(k);await page.waitForTimeout(ms);};
 await click(800,530);await key('e');await key('e',2800);
 await page.screenshot({path:path.join(output,'fetch.png')});
 await key('e');await key('e',2500);
 await click(685,550,1800);await key('q',3400);
 await page.screenshot({path:path.join(output,'discovery.png')});
 await key('e');await click(666,445,1600);await key('e',6500);
 await page.screenshot({path:path.join(output,'signal.png')});
 await click(475,596,4000);await key('e');await click(397,606,1400);await key('e',2700);
 await page.screenshot({path:path.join(output,'ending.png')});
 console.log('Browser error count:',errors.length);
 await browser.close();
 if(errors.some(x=>/SCRIPT ERROR|Parse Error|Uncaught|Invalid|Cannot|not found/i.test(x)))process.exit(1);
})().catch(e=>{console.error(e);process.exit(1)});
